// Returns list of people this user can message:
//   parent  → teachers of their children
//   teacher → parents of their students

router.get('/contacts', async (req, res) => {
  try {
    const userEmail = (req.query.userEmail || '').trim().toLowerCase();
    if (!userEmail) return res.status(400).json({ error: 'userEmail required' });

    // ── Demo fallback: return mock contacts for test accounts ──
    if (DEMO_RELATIONSHIPS[userEmail]) {
      const rel = DEMO_RELATIONSHIPS[userEmail];
      return res.json(rel.teachers.map(t => ({
        id:      t.email,
        name:    t.name,
        email:   t.email,
        role:    'teacher',
        context: `Teacher of ${rel.children.map(c => c.name).join(', ')}`,
      })));
    }
    if (DEMO_TEACHER_CONTACTS[userEmail]) {
      return res.json(DEMO_TEACHER_CONTACTS[userEmail].map(p => ({
        id:      p.email,
        name:    p.name,
        email:   p.email,
        role:    'parent',
        context: `Parent of ${p.childName}`,
      })));
    }

    // Look up the user's id, role, and school
    const { data: me, error: meErr } = await supabase
      .from('users')
      .select('id, role, name, school, school_id')
      .eq('email', userEmail)
      .single();

    if (meErr || !me) return res.status(404).json({ error: 'User not found' });

    // Dual-role accounts (roles: ['teacher','parent']) store a single base `role`
    // in the users table that may not match which profile is currently active
    // (e.g. teacheraivorah@gmail.com is stored as role='parent' but is actively
    // used as a teacher). The client knows its own active role — prefer that
    // over the raw DB column so contacts resolve for the profile actually in use.
    const requestedRole = (req.query.role || '').trim().toLowerCase();
    const effectiveRole = (requestedRole === 'teacher' || requestedRole === 'parent') ? requestedRole : me.role;

    if (effectiveRole === 'parent') {
      // 1. Get parent's children
      const { data: links } = await supabase
        .from('parent_children')
        .select('child_id, users!parent_children_child_id_fkey(id, name)')
        .eq('parent_email', userEmail);

      if (!links || links.length === 0) return res.json([]);

      const childIds   = links.map(l => l.child_id);
      const childNames = {};
      links.forEach(l => { childNames[l.child_id] = l.users?.name || 'Your child'; });

      // 2. Find teachers assigned to those children via teacher_student table
      const { data: tsLinks } = await supabase
        .from('teacher_student')
        .select('teacher_id, student_id')
        .in('student_id', childIds);

      if (!tsLinks || tsLinks.length === 0) return res.json([]);

      // Map teacher_id → [child names they teach from this parent]
      const teacherChildMap = {};
      tsLinks.forEach(ts => {
        if (!teacherChildMap[ts.teacher_id]) teacherChildMap[ts.teacher_id] = [];
        const cname = childNames[ts.student_id];
        if (cname) teacherChildMap[ts.teacher_id].push(cname);
      });

      const teacherIds = Object.keys(teacherChildMap);

      // 3. Get teacher user details
      const { data: teachers } = await supabase
        .from('users')
        .select('id, name, email')
        .in('id', teacherIds);

      const contacts = (teachers || []).map(t => ({
        id:      t.id,
        name:    t.name || t.email,
        email:   t.email,
        role:    'teacher',
        context: `Teacher of ${[...new Set(teacherChildMap[t.id] || [])].join(', ')}`,
      }));

      return res.json(contacts);
    }

    if (effectiveRole === 'teacher') {
      const contacts = [];

      // 1. Get students this teacher is assigned to via teacher_student table
      const { data: tsLinks } = await supabase
        .from('teacher_student')
        .select('student_id')
        .eq('teacher_id', me.id);
      const studentIds = (tsLinks || []).map(ts => ts.student_id);

      if (studentIds.length) {
        // 2. Get student names
        const { data: students } = await supabase
          .from('users')
          .select('id, name')
          .in('id', studentIds);
        const studentNames = {};
        (students || []).forEach(s => { studentNames[s.id] = s.name; });

        // 3. Get parent links for those students
        const { data: parentLinks } = await supabase
          .from('parent_children')
          .select('parent_email, child_id')
          .in('child_id', studentIds);

        // Build parent_email → child names
        const parentChildMap = {};
        (parentLinks || []).forEach(p => {
          if (!parentChildMap[p.parent_email]) parentChildMap[p.parent_email] = [];
          const cname = studentNames[p.child_id];
          if (cname) parentChildMap[p.parent_email].push(cname);
        });

        const parentEmails = Object.keys(parentChildMap);
        if (parentEmails.length) {
          // 4. Get parent user details
          const { data: parents } = await supabase
            .from('users')
            .select('id, name, email')
            .in('email', parentEmails);

          contacts.push(...(parents || []).map(p => ({
            id:      p.id,
            name:    p.name || p.email,
            email:   p.email,
            role:    'parent',
            context: `Parent of ${[...new Set(parentChildMap[p.email] || [])].join(', ')}`,
          })));
        }
      }

      // 5. Staff directory — other teachers and school admins at the same
      // school, so a teacher can reach a colleague or their admin directly
      // instead of only ever messaging parents.
      if (me.school_id) {
        const { data: staff } = await supabase
          .from('users')
          .select('id, name, email, role')
          .eq('school_id', me.school_id)
          .in('role', ['teacher', 'school_admin'])
          .neq('email', userEmail);

        contacts.push(...(staff || []).map(s => ({
          id:      s.id,
          name:    s.name || s.email,
          email:   s.email,
          role:    s.role,
          context: s.role === 'school_admin' ? 'School Administrator' : 'Teacher',
        })));
      }

      return res.json(contacts);
    }

    if (effectiveRole === 'school_admin') {
      // A school admin's contacts are every other staff member (teachers +
      // fellow admins) at their own school — the internal-chat counterpart
      // to the teacher branch above.
      if (!me.school_id) return res.json([]);
      const { data: staff } = await supabase
        .from('users')
        .select('id, name, email, role')
        .eq('school_id', me.school_id)
        .in('role', ['teacher', 'school_admin'])
        .neq('email', userEmail);

      return res.json((staff || []).map(s => ({
        id:      s.id,
        name:    s.name || s.email,
        email:   s.email,
        role:    s.role,
        context: s.role === 'school_admin' ? 'School Administrator' : 'Teacher',
      })));
    }

    if (effectiveRole === 'student') {
      // Students can message their own linked parent(s) — this branch was
      // previously missing entirely, so it silently fell through to the
      // empty-contacts response below regardless of whether a parent existed.
      const { data: parentLinks } = await supabase
        .from('parent_children')
        .select('parent_email')
        .eq('child_id', me.id);

      if (!parentLinks || parentLinks.length === 0) return res.json([]);

      const parentEmails = [...new Set(parentLinks.map(p => p.parent_email))];
      const { data: parents } = await supabase
        .from('users')
        .select('id, name, email')
        .in('email', parentEmails);

      const contacts = (parents || []).map(p => ({
        id:      p.id,
        name:    p.name || p.email,
        email:   p.email,
        role:    'parent',
        context: 'Your parent',
      }));

      return res.json(contacts);
    }

    res.json([]);
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

// ── GET /messages/conversations?userEmail=&role= ─────────
// Returns unique conversation threads for a user, filtered by their active role.
// role=teacher → show conversations with parents only
// role=parent  → show conversations with teachers only
router.get('/conversations', async (req, res) => {
  try {
    const userEmail  = (req.query.userEmail || '').trim().toLowerCase();
    const activeRole = (req.query.role      || '').trim().toLowerCase(); // 'teacher' | 'parent' | ''
    if (!userEmail) return res.status(400).json({ error: 'userEmail required' });

    // Get all messages where user is sender or recipient
    const { data, error } = await supabase
      .from('messages')
      .select('*')
      .or(`sender_email.eq.${userEmail},recipient_email.eq.${userEmail}`)
      .order('created_at', { ascending: false });

    if (error) return res.status(500).json({ error: error.message });

    // Collect unique other-party emails for role lookup
    const otherEmails = [...new Set(
      (data ?? []).map(msg =>
        msg.sender_email === userEmail ? msg.recipient_email : msg.sender_email
      ).filter(e => e && e !== userEmail)
    )];

    // Batch-lookup roles + current names from users table — the message row's
    // own sender_name/recipient_name is a snapshot taken when that message was
    // sent, so it can be blank/stale (e.g. account had no name yet). Always
    // prefer the live name over that snapshot.
    const roleMap = {};
    const nameMap = {};
    if (otherEmails.length > 0) {
      const { data: users } = await supabase
        .from('users')
        .select('email, role, name')
        .in('email', otherEmails);
      (users ?? []).forEach(u => { roleMap[u.email] = u.role; if (u.name) nameMap[u.email] = u.name; });
    }

    // Group into threads — keyed by the other person's email
    const threadMap = {};
    (data ?? []).forEach(msg => {
      const otherEmail = msg.sender_email === userEmail ? msg.recipient_email : msg.sender_email;
      const otherName  = msg.sender_email === userEmail ? msg.recipient_name  : msg.sender_name;
      // Use DB role lookup as source of truth; fall back to sender_role for incoming messages
      const otherRole  = roleMap[otherEmail] || (msg.sender_email !== userEmail ? msg.sender_role : null) || 'parent';

      // Filter by active role: a teacher sees parents AND staff (other
      // teachers, school admins) — a school's internal chat, not just the
      // parent-facing side. A parent sees staff too (teacher OR school_admin —
      // a parent's contact is labeled 'teacher' in the contacts list, but the
      // live DB role looked up here can legitimately be 'school_admin', and
      // that mismatch silently dropped the conversation from the parent's
      // list entirely, even though the thread itself still worked fine).
      // Aivorah system reminders use sender_role 'teacher' (system@aivorah.com),
      // so they appear in the parent's (and student's) thread list automatically.
      if (activeRole === 'teacher' && !['parent', 'teacher', 'school_admin'].includes(otherRole)) return;
      if (activeRole === 'parent'  && !['teacher', 'school_admin'].includes(otherRole)) return;

      if (!threadMap[otherEmail]) {
        threadMap[otherEmail] = {
          otherEmail,
          otherName:  nameMap[otherEmail] || otherName || otherEmail,
          otherRole,
          lastMessage: msg.content,
          lastMessageAt: msg.created_at,
          unreadCount: 0,
        };
      }
      // Count unread messages sent TO this user
      if (msg.recipient_email === userEmail && !msg.read_at) {
        threadMap[otherEmail].unreadCount += 1;
      }
    });

    res.json(Object.values(threadMap));
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

// ── GET /messages/thread?userEmail=&otherEmail= ──────────
// Returns all messages in a conversation thread
router.get('/thread', async (req, res) => {
  try {
    const userEmail  = (req.query.userEmail  || '').trim().toLowerCase();
    const otherEmail = (req.query.otherEmail || '').trim().toLowerCase();
    if (!userEmail || !otherEmail) return res.status(400).json({ error: 'userEmail and otherEmail required' });

    const { data, error } = await supabase
      .from('messages')
      .select('*')
      .or(
        `and(sender_email.eq.${userEmail},recipient_email.eq.${otherEmail}),` +
        `and(sender_email.eq.${otherEmail},recipient_email.eq.${userEmail})`
      )
      .order('created_at', { ascending: true });

    if (error) return res.status(500).json({ error: error.message });

    // Resolve each reply's quoted original (snippet + sender), so the client
    // can render a Toddle/WhatsApp-style quote strip without a second round trip.
    const replyIds = [...new Set((data ?? []).map((m) => m.reply_to_id).filter(Boolean))];
    let repliedTo = {};
    if (replyIds.length) {
      const { data: originals } = await supabase.from('messages').select('id, content, sender_name, sender_email').in('id', replyIds);
      repliedTo = Object.fromEntries((originals ?? []).map((o) => [o.id, o]));
    }
    // Group reactions per message: { emoji -> count, mine -> my current emoji }.
    const msgIds = (data ?? []).map((m) => m.id);
    let reactionsByMsg = {};
    if (msgIds.length) {
      const { data: reactions } = await supabase.from('message_reactions').select('message_id, user_email, emoji').in('message_id', msgIds);
      for (const r of reactions || []) {
        if (!reactionsByMsg[r.message_id]) reactionsByMsg[r.message_id] = { counts: {}, mine: null };
        reactionsByMsg[r.message_id].counts[r.emoji] = (reactionsByMsg[r.message_id].counts[r.emoji] || 0) + 1;
        if (r.user_email === userEmail) reactionsByMsg[r.message_id].mine = r.emoji;
      }
    }

    const withReplies = (data ?? []).map((m) => ({
      ...m,
      reply_to: m.reply_to_id && repliedTo[m.reply_to_id] ? {
        id: repliedTo[m.reply_to_id].id,
        senderName: repliedTo[m.reply_to_id].sender_name,
        content: repliedTo[m.reply_to_id].content,
      } : null,
      reactions: reactionsByMsg[m.id]?.counts || {},
      myReaction: reactionsByMsg[m.id]?.mine || null,
    }));

    res.json(withReplies);
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

// ── POST /messages/:id/react  { userEmail, emoji } ──────────
// Toggle: tapping the same emoji again removes it; a different emoji replaces it.
router.post('/:id/react', async (req, res) => {
  try {
    const { id } = req.params;
    const userEmail = (req.body?.userEmail || '').trim().toLowerCase();
    const emoji = req.body?.emoji;
    if (!userEmail || !emoji) return res.status(400).json({ error: 'userEmail and emoji required' });

    const { data: existing } = await supabase.from('message_reactions').select('id, emoji').eq('message_id', id).eq('user_email', userEmail).maybeSingle();
    if (existing?.emoji === emoji) {
      await supabase.from('message_reactions').delete().eq('id', existing.id);
      return res.json({ ok: true, removed: true });
    }
    const { error } = await supabase.from('message_reactions').upsert(
      { message_id: id, user_email: userEmail, emoji },
      { onConflict: 'message_id,user_email' }
    );
    if (error) throw error;
    res.json({ ok: true });
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

// ── POST /messages/upload ─────────────────────────────────
// Upload a file attachment to Cloudinary, returns { url, name, size, type }.
// (Stored on Cloudinary — not local disk — so attachments are reachable from
//  any Cloud Run instance behind the load balancer.)
router.post('/upload', upload.single('file'), async (req, res) => {
  if (!req.file) return res.status(400).json({ error: 'No file uploaded' });
  const ext = path.extname(req.file.originalname).toLowerCase().replace('.', '');
  try {
    const mime    = req.file.mimetype || 'application/octet-stream';
    const dataUri = `data:${mime};base64,${req.file.buffer.toString('base64')}`;
    const result  = await cloudinary.uploader.upload(dataUri, {
      folder:        'ai_mentor/message_attachments',
      public_id:     `att_${Date.now()}`,
      resource_type: 'auto', // handles both images and PDFs
    });
    res.json({
      url:  result.secure_url,
      name: req.file.originalname,
      size: req.file.size,
      type: ext,
    });
  } catch (err) {
    console.error('[messages/upload]', err.message);
    res.status(500).json({ error: 'Could not upload the file. Please try again.' });
  }
});

