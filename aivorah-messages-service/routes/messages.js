// ── File upload config ──────────────────────────────────
const MAX_FILE_SIZE = 10 * 1024 * 1024; // 10 MB
const ALLOWED_TYPES = /^(pdf|png|jpg|jpeg|gif|webp)$/; // images and PDFs only (issue #45)

// Keep the file in memory so we can stream it straight to Cloudinary — Cloud Run
// instances have ephemeral, per-instance disks, so local files aren't shared.
const upload = multer({
  storage: multer.memoryStorage(),
  limits: { fileSize: MAX_FILE_SIZE },
  fileFilter: (_req, file, cb) => {
    const ext = path.extname(file.originalname).toLowerCase().replace('.', '');
    const mime = file.mimetype || '';
    const validExt  = ALLOWED_TYPES.test(ext);
    const validMime = /^(image\/(jpeg|png|gif|webp)|application\/pdf)$/.test(mime);
    if (validExt && validMime) return cb(null, true);
    cb(new Error('Only images (JPG, PNG, GIF, WebP) and PDFs are allowed'));
  },
});

// ── GET /messages/unread-count?userEmail= ───────────────
// Returns total unread count + latest unread message for bell notification

const NOTIFICATION_DEBUG = ['1', 'true', 'yes', 'on'].includes(
  String(process.env.NOTIFICATION_DEBUG || '').trim().toLowerCase()
);

function logNotificationDebug(message, meta = {}) {
  if (!NOTIFICATION_DEBUG) return;
  console.log(`[messages.notifications] ${message}`, meta);
}

// Assignment/challenge notification messages are auto-generated by the system.
// They should NOT appear as unread chat messages — only as notification items.
const SYSTEM_NOTIF_PREFIXES = [
  'New Quiz assigned:',
  'New Assignment assigned:',
  'New Challenge assigned:',
];
// Strip an optional "[Child Name] " prefix that assignment/challenge notifications
// now carry, so categorization still works (otherwise these auto-messages leak into
// the real-chat count and never appear as proper assignment/challenge notifications).
function stripChildPrefix(content) {
  return String(content || '').trim().replace(/^\[[^\]]*\]\s*/, '');
}
function isSystemNotification(content) {
  if (typeof content !== 'string') return false;
  const c = stripChildPrefix(content);
  if (c.startsWith('SCHEDULE_CARD|')) return true; // schedule-event card sent to parents
  return SYSTEM_NOTIF_PREFIXES.some(p => c.startsWith(p));
}

function toMessagePreview(content) {
  if (typeof content !== 'string') return '';
  const trimmed = content.trim();
  if (!trimmed) return '';

  if (trimmed.startsWith('{')) {
    try {
      const parsed = JSON.parse(trimmed);
      const text = typeof parsed?.text === 'string' ? parsed.text.trim() : '';
      if (text) return text.slice(0, 60);
      if (parsed?.attachment?.name) {
        return `Shared a file: ${String(parsed.attachment.name).trim().slice(0, 40)}`;
      }
    } catch (_) {
      // Fall through to plain-text preview.
    }
  }
  return trimmed.slice(0, 60);
}

// GET /messages/unread-count?userEmail=
// Returns total unread count + latest unread message for bell notification
router.get('/unread-count', async (req, res) => {
  try {
    const userEmail = (req.query.userEmail || '').trim().toLowerCase();
    if (!userEmail) return res.status(400).json({ error: 'userEmail required' });

    const { count, error: countError } = await supabase
      .from('messages')
      .select('id', { head: true, count: 'exact' })
      .eq('recipient_email', userEmail)
      .is('read_at', null);

    if (countError) return res.status(500).json({ error: countError.message });

    const safeCount = Number.isFinite(count) ? Number(count) : 0;
    let latest = null;

    if (safeCount > 0) {
      const { data, error } = await supabase
        .from('messages')
        .select('id, sender_name, sender_email, content, created_at')
        .eq('recipient_email', userEmail)
        .is('read_at', null)
        .order('created_at', { ascending: false })
        .limit(1)
        .maybeSingle();

      if (error) return res.status(500).json({ error: error.message });

      if (data) {
        latest = {
          id: data.id,
          senderName: data.sender_name || data.sender_email || 'Someone',
          senderEmail: data.sender_email || '',
          preview: toMessagePreview(data.content),
          createdAt: data.created_at,
        };
      } else {
        logNotificationDebug('Unread count > 0 but latest unread row is missing', {
          userEmail,
          count: safeCount,
        });
      }
    }

    logNotificationDebug('Unread count resolved', {
      userEmail,
      count: safeCount,
      latestId: latest?.id || null,
    });

    res.json({ count: safeCount, latest });
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

// ── GET /messages/notifications-summary?userEmail=&studentId=&since= ──────────
// Returns unread message count (real chat only) + new assignment/challenge counts
// + notification items fetched directly from the assignments table (Google Classroom style).
router.get('/notifications-summary', async (req, res) => {
  try {
    const userEmail  = (req.query.userEmail  || '').trim().toLowerCase();
    const studentId  = (req.query.studentId  || '').trim();
    const since      = req.query.since || null;
    // Challenges can have their own "seen" baseline (separate toggle); fall back to `since`.
    const challengeSince = req.query.challengeSince || since;
    const eventSince     = req.query.eventSince || since;

    if (!userEmail) return res.status(400).json({ error: 'userEmail required' });

    // Resolve userId + curriculum/grade/school for this user
    let userId = null, studentCurriculum = null, studentGrade = null, studentSchool = null, userRole = null;
    const { data: uRow } = await supabase
      .from('users')
      .select('id, curriculum, grade, school, role, created_at')
      .eq('email', userEmail)
      .maybeSingle();
    if (uRow) {
      userId = studentId || uRow.id;
      studentCurriculum = uRow.curriculum || null;
      studentGrade = uRow.grade || null;
      studentSchool = uRow.school || null;
      userRole = uRow.role || null;
    } else if (studentId && !studentId.includes('@')) {
      userId = studentId;
    }

    // ── Registration cap (Google Classroom / Canvas model): the Bell must never
    // surface an alert for something created BEFORE this account existed. A
    // brand-new signup lands on the dashboard with the client's default 7-day
    // lookback and would otherwise see a week of pre-existing class broadcasts.
    // Cap every "since" below at the LATER of the client's value and the user's
    // own registration timestamp. (The Assignments screen is untouched — it
    // shows full due workload regardless of when the account was created.)
    const userCreatedAtMs = uRow?.created_at && Number.isFinite(Date.parse(uRow.created_at))
      ? Date.parse(uRow.created_at) : 0;
    function capSince(clientSinceIso) {
      const clientMs = clientSinceIso && Number.isFinite(Date.parse(clientSinceIso)) ? Date.parse(clientSinceIso) : 0;
      const effectiveMs = Math.max(clientMs, userCreatedAtMs);
      return effectiveMs > 0 ? new Date(effectiveMs).toISOString() : null;
    }
    const effectiveSince          = capSince(since);
    const effectiveChallengeSince = capSince(challengeSince);
    const effectiveEventSince     = capSince(eventSince);

    // 1. Real chat messages (unread) — students have no Messages, so this is 0 for them
    const msgQ = supabase
      .from('messages')
      .select('id, sender_name, sender_email, content, created_at')
      .eq('recipient_email', userEmail)
      .is('read_at', null)
      .order('created_at', { ascending: false })
      .limit(20);

    // 2. New assignments since last seen (personal + class-wide).
    // Assignment notifications are for STUDENTS only — teachers create them and
    // parents are notified via real messages, so notifying them here is noise.
    const isStudent = userRole === 'student' || (!userRole && userId);

    // Which teachers is this student linked to? A teacher's "All students"
    // broadcast must only notify that teacher's own students (mirrors /assignments).
    let studentTeacherIds = [];
    if (isStudent && userId) {
      const { data: tlinks } = await supabase
        .from('teacher_student')
        .select('teacher_id')
        .eq('student_id', userId);
      studentTeacherIds = [...new Set((tlinks || []).map(l => l.teacher_id).filter(Boolean))];
    }

    let personalAssignQ = null;
    let classAssignQ = null;
    if (isStudent && userId) {
      personalAssignQ = supabase
        .from('assignments')
        .select('id, title, subject, type, created_at, created_by_id, student_id')
        .eq('student_id', userId)
        .order('created_at', { ascending: false })
        .limit(10);
      if (effectiveSince) personalAssignQ = personalAssignQ.gt('created_at', effectiveSince);

      classAssignQ = supabase
        .from('assignments')
        .select('id, title, subject, type, created_at, created_by_id, created_by_role, student_id')
        .is('student_id', null)
        .order('created_at', { ascending: false })
        .limit(10);
      // Curriculum partition — mirror GET /assignments exactly: a class-wide item
      // shows if its curriculum is null (untagged → everyone) OR matches the
      // student's. A student with no curriculum recorded only sees untagged ones,
      // never items tagged for another curriculum.
      classAssignQ = studentCurriculum
        ? classAssignQ.or(`curriculum.is.null,curriculum.eq."${studentCurriculum}"`)
        : classAssignQ.is('curriculum', null);
      if (studentGrade) classAssignQ = classAssignQ.or(`grade.is.null,grade.eq."${studentGrade}"`);
      if (effectiveSince) classAssignQ = classAssignQ.gt('created_at', effectiveSince);
      // Teacher broadcasts only from this student's own teachers; non-teacher
      // (admin/school) broadcasts stay curriculum-wide.
      classAssignQ = studentTeacherIds.length > 0
        ? classAssignQ.or(`created_by_role.neq.teacher,created_by_id.in.(${studentTeacherIds.join(',')})`)
        : classAssignQ.neq('created_by_role', 'teacher');
    }

    // 3. New challenges — fetch the actual rows so each can deep-link to its challenge
    let challengeQ = null;
    if (isStudent && userId) {
      challengeQ = supabase
        .from('challenge_assignments')
        .select('id, challenge_id, assigned_by_id, assigned_by_role, created_at')
        .eq('student_id', userId)
        .neq('status', 'completed')
        .order('created_at', { ascending: false })
        .limit(10);
      if (effectiveChallengeSince) challengeQ = challengeQ.gt('created_at', effectiveChallengeSince);
    }

    // 4. New schedule events created FOR this student by a teacher or parent.
    //    Class-wide (student_id = 'all') events only from this student's own teachers.
    let eventQ = null;
    if (isStudent && userId) {
      const classWide = studentTeacherIds.length > 0
        ? `,and(student_id.eq.all,created_by.eq.teacher,created_by_id.in.(${studentTeacherIds.join(',')}))`
        : '';
      eventQ = supabase
        .from('schedule_events')
        .select('id, title, event_date, type, created_by, created_by_id, student_id, assignment_id, created_at, note')
        .or(`student_id.eq.${userId}${classWide}`)
        .in('created_by', ['teacher', 'parent'])
        .order('created_at', { ascending: false })
        .limit(20); // room for due reminders next to events the V2 feed owns
      if (effectiveEventSince) eventQ = eventQ.gt('created_at', effectiveEventSince);
    }

    // 5. New daily tasks a PARENT assigned to this student. Previously these landed
    //    silently — the student got no bell alert (unlike challenges/assignments).
    let taskQ = null;
    if (isStudent && userId) {
      taskQ = supabase
        .from('parent_daily_tasks')
        .select('id, label, created_at')
        .eq('child_id', userId)
        .order('created_at', { ascending: false })
        .limit(10);
      if (effectiveEventSince) taskQ = taskQ.gt('created_at', effectiveEventSince);
    }

    const [msgRes, personalAssignRes, classAssignRes, challengeRes, eventRes, taskRes] = await Promise.all([
      msgQ,
      personalAssignQ || Promise.resolve({ data: [] }),
      classAssignQ    || Promise.resolve({ data: [] }),
      challengeQ      || Promise.resolve({ data: [] }),
      eventQ          || Promise.resolve({ data: [] }),
      taskQ           || Promise.resolve({ data: [] }),
    ]);

    // Split incoming messages: real chat vs system notifications (assignment/challenge alerts)
    const rawMsgs = msgRes.data || [];
    const allMsgs = rawMsgs.filter(m => !isSystemNotification(m.content));
    const msgCount = allMsgs.length;
    const latest   = allMsgs[0] ? {
      id:          allMsgs[0].id,
      senderName:  allMsgs[0].sender_name || 'Someone',
      senderEmail: allMsgs[0].sender_email || '',
      preview:     toMessagePreview(allMsgs[0].content),
      createdAt:   allMsgs[0].created_at,
    } : null;

    // For parents: system-prefix messages in their inbox are assignment/challenge alerts
    // inserted by the assignments route when a teacher assigns to their child.
    // Registration cap applies here too: msgQ has no time filter at all (it's
    // unread-only), so without this a parent whose account predates a backfilled/
    // migrated system message could still see a pre-registration alert. Same
    // Google Classroom / Canvas rule as the assignment/challenge/event queries above.
    const isParent = userRole === 'parent';
    const parentSystemMsgs = isParent
      ? rawMsgs.filter(m => isSystemNotification(m.content) && (!userCreatedAtMs || Date.parse(m.created_at) > userCreatedAtMs))
      : [];
    const parentAssignMsgs = parentSystemMsgs.filter(m => {
      const c = stripChildPrefix(m.content);
      return c.startsWith('New Assignment assigned:') || c.startsWith('New Quiz assigned:');
    });
    const parentChallengeMsgs = parentSystemMsgs.filter(m =>
      stripChildPrefix(m.content).startsWith('New Challenge assigned:')
    );
    const parentEventMsgs = parentSystemMsgs.filter(m =>
      stripChildPrefix(m.content).startsWith('SCHEDULE_CARD|')
    );
    const parentPortfolioMsgs = parentSystemMsgs.filter(m =>
      stripChildPrefix(m.content).startsWith('PORTFOLIO_CARD|')
    );

    // Merge personal + class assignments (students only), dedupe by id
    const allAssigns = [...(personalAssignRes.data || []), ...(classAssignRes.data || [])];
    const seenIds = new Set();
    let uniqueAssigns = allAssigns.filter(a => { if (seenIds.has(a.id)) return false; seenIds.add(a.id); return true; });

    // Fetch creator names + schools in one shot
    const creatorIds = [...new Set(uniqueAssigns.map(a => a.created_by_id).filter(Boolean))];
    let creatorMap = {};
    let creatorSchoolMap = {};
    if (creatorIds.length > 0) {
      const { data: creators } = await supabase.from('users').select('id, name, school').in('id', creatorIds);
      (creators || []).forEach(c => { creatorMap[c.id] = c.name || 'Teacher'; creatorSchoolMap[c.id] = c.school || null; });
    }

    // School scoping: a class-wide assignment from a different school must NOT notify
    // this student (same curriculum but different school). Personal items are explicit.
    uniqueAssigns = uniqueAssigns.filter(a => {
      if (a.student_id !== null) return true;
      const cSchool = a.created_by_id ? creatorSchoolMap[a.created_by_id] : null;
      if (cSchool && studentSchool && cSchool !== studentSchool) return false;
      return true;
    });

    const challengeRows  = challengeRes.data || [];
    const assignCount    = isParent ? parentAssignMsgs.length : uniqueAssigns.length;
    const challengeCount = isParent ? parentChallengeMsgs.length : challengeRows.length;

    // Fetch challenge titles for the per-challenge notification items
    const challengeIds = [...new Set(challengeRows.map(r => r.challenge_id).filter(Boolean))];
    let challengeMap = {};
    if (challengeIds.length > 0) {
      const { data: chs } = await supabase.from('challenges').select('id, title, subject').in('id', challengeIds);
      (chs || []).forEach(c => { challengeMap[c.id] = c; });
    }

    // Build notification items
    let assignmentItems = [];
    if (isParent) {
      // Parent: build items from system messages
      assignmentItems = parentAssignMsgs.map(m => {
        const c = stripChildPrefix(m.content);
        const titleMatch = c.match(/^New (?:Assignment|Quiz) assigned: "([^"]+)"/);
        const subjectMatch = c.match(/\(([^)]+)\)/);
        return {
          id:         m.id,
          type:       c.startsWith('New Quiz') ? 'quiz' : 'assignment',
          title:      titleMatch ? titleMatch[1] : 'New Assignment',
          subtitle:   subjectMatch ? subjectMatch[1] : '',
          senderName: m.sender_name || 'Aivorah',
          createdAt:  m.created_at,
        };
      });
    } else {
      assignmentItems = uniqueAssigns.map(a => ({
        id:         a.id,
        type:       a.type === 'quiz' ? 'quiz' : 'assignment',
        title:      a.title || 'New Assignment',
        subtitle:   [a.subject, creatorMap[a.created_by_id]].filter(Boolean).join(' · '),
        senderName: creatorMap[a.created_by_id] || 'Teacher',
        createdAt:  a.created_at,
      }));
    }

    const challengeItems = isParent
      ? parentChallengeMsgs.map(m => {
          const c = stripChildPrefix(m.content);
          const titleMatch = c.match(/^New Challenge assigned: "([^"]+)"/);
          const subjectMatch = c.match(/\(([^)]+)\)/);
          return {
            id: m.id, type: 'challenge',
            title: titleMatch ? titleMatch[1] : 'New Challenge',
            subtitle: subjectMatch ? subjectMatch[1] : '',
            senderName: m.sender_name || 'Aivorah', createdAt: m.created_at,
          };
        })
      : challengeRows.map(r => ({
          id:         r.challenge_id,
          type:       'challenge',
          title:      challengeMap[r.challenge_id]?.title || 'New Challenge',
          subtitle:   [challengeMap[r.challenge_id]?.subject, 'Challenge'].filter(Boolean).join(' · '),
          senderName: r.assigned_by_role === 'parent' ? 'Your parent' : 'Your teacher',
          createdAt:  r.created_at,
        }));

    // Schedule events created for the student by a teacher/parent — students see
    // these via the schedule_events query above; parents get a rich message card
    // (SCHEDULE_CARD|childName|title|date|startTime|type) parsed into the same
    // notification item shape here.
    const eventRows = (eventRes.data || []).filter(e =>
      e.student_id !== 'all' ||
      (e.created_by === 'teacher' && e.created_by_id && studentTeacherIds.includes(e.created_by_id)));
    const eventCount = isParent ? parentEventMsgs.length : eventRows.length;
    const eventItems = isParent
      ? parentEventMsgs.map(m => {
          const c = stripChildPrefix(m.content);
          const [, childName, title, date, startTime] = c.split('|');
          return {
            id:         'evt_' + m.id,
            type:       'event',
            autoDue:    false,
            title:      title || 'New Event',
            subtitle:   [date, startTime, childName ? `for ${childName}` : ''].filter(Boolean).join(' · '),
            senderName: m.sender_name || 'Aivorah',
            createdAt:  m.created_at,
          };
        })
      : eventRows.map(e => ({
          id:         'evt_' + e.id,
          type:       'event',
          // Preserve the source schedule type ('challenge' | 'deadline' | 'study' …)
          // so the client can gate a challenge's due-date event under the Challenge
          // Updates toggle instead of Assignment Alerts.
          srcType:    e.type || null,
          // Due-date reminders auto-created with an assignment/challenge; other events are owned by V2 'event_scheduled'.
          autoDue:    !!e.assignment_id,
          title:      e.title || 'New Event',
          subtitle:   [e.event_date, e.note].filter(Boolean).join(' · '),
          senderName: e.created_by === 'parent' ? 'Your parent' : 'Your teacher',
          createdAt:  e.created_at,
        }));

    const portfolioItems = parentPortfolioMsgs.map(m => {
      const c = stripChildPrefix(m.content);
      const [, postId, text, grade, section] = c.split('|');
      return {
        id:         m.id,
        type:       'portfolio',
        postId:     postId,
        grade:      grade,
        section:    section,
        title:      'Class Portfolio',
        subtitle:   text || 'New portfolio post',
        senderName: m.sender_name || 'Aivorah',
        createdAt:  m.created_at,
      };
    });

    // Parent-assigned daily tasks (students only). Counted alongside events so the
    // bell respects the same Assignment Alerts toggle.
    const taskRows = isParent ? [] : (taskRes.data || []);
    const taskItems = taskRows.map(t => ({
      id:         'task_' + t.id,
      type:       'task',
      title:      'New daily task',
      subtitle:   [t.label, 'from your parent'].filter(Boolean).join(' · '),
      senderName: 'Your parent',
      createdAt:  t.created_at,
    }));

    const notificationItems = [...assignmentItems, ...challengeItems, ...eventItems, ...taskItems, ...portfolioItems]
      .sort((a, b) => Date.parse(b.createdAt || 0) - Date.parse(a.createdAt || 0))
      .slice(0, 20);

    res.json({ messages: msgCount, assignments: assignCount, challenges: challengeCount, events: eventCount + portfolioItems.length + taskItems.length, latest, notificationItems });
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

// POST /messages/mark-read
// Marks all unread notifications for the user as read.
router.post('/mark-read', async (req, res) => {
  try {
    const userEmail = (req.body?.userEmail || '').trim().toLowerCase();
    if (!userEmail) return res.status(400).json({ error: 'userEmail required' });

    const readAt = new Date().toISOString();
    const { data: updatedRows, error: updateError } = await supabase
      .from('messages')
      .update({ read_at: readAt })
      .eq('recipient_email', userEmail)
      .is('read_at', null)
      .select('id');

    if (updateError) return res.status(500).json({ error: updateError.message });

    const markedCount = Array.isArray(updatedRows) ? updatedRows.length : 0;
    const { count: unreadCount, error: unreadError } = await supabase
      .from('messages')
      .select('id', { head: true, count: 'exact' })
      .eq('recipient_email', userEmail)
      .is('read_at', null);

    if (unreadError) return res.status(500).json({ error: unreadError.message });

    const payload = {
      success: true,
      markedCount,
      unreadCount: Number.isFinite(unreadCount) ? Number(unreadCount) : 0,
      markedAt: readAt,
    };

    logNotificationDebug('Marked unread messages as read', {
      userEmail,
      markedCount,
      unreadCount: payload.unreadCount,
    });

    res.json(payload);
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

// POST /messages/mark-system-read
// Marks a user's UNREAD system-notification messages (assignment/quiz/challenge
// alerts) as read — by kind. Parents' assignment/challenge bell counts are backed
// by these auto-generated messages, so reading/tapping a notification must persist
// the read state server-side, otherwise the next poll re-surfaces the same alert.
router.post('/mark-system-read', async (req, res) => {
  try {
    const userEmail = (req.body?.userEmail || '').trim().toLowerCase();
    const kind      = (req.body?.kind || 'all').trim().toLowerCase(); // 'assignment' | 'challenge' | 'all'
    if (!userEmail) return res.status(400).json({ error: 'userEmail required' });

    // Prefixes to match for this kind.
    const prefixes = kind === 'assignment'
      ? ['New Quiz assigned:', 'New Assignment assigned:']
      : kind === 'challenge'
        ? ['New Challenge assigned:']
        : SYSTEM_NOTIF_PREFIXES;

    // Fetch unread system messages for this recipient, then filter by prefix in JS
    // (Supabase has no clean multi-prefix "starts-with" filter).
    const { data: unread, error: fetchErr } = await supabase
      .from('messages')
      .select('id, content')
      .eq('recipient_email', userEmail)
      .is('read_at', null);
    if (fetchErr) return res.status(500).json({ error: fetchErr.message });

    const ids = (unread || [])
      .filter(m => typeof m.content === 'string' && prefixes.some(p => stripChildPrefix(m.content).startsWith(p)))
      .map(m => m.id);

    if (ids.length === 0) return res.json({ success: true, markedCount: 0 });

    const readAt = new Date().toISOString();
    const { error: updErr } = await supabase
      .from('messages')
      .update({ read_at: readAt })
      .in('id', ids);
    if (updErr) return res.status(500).json({ error: updErr.message });

    logNotificationDebug('Marked system notifications as read', { userEmail, kind, markedCount: ids.length });
    res.json({ success: true, markedCount: ids.length });
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

// PATCH /messages/read?userEmail=&otherEmail=
// Mark all messages from otherEmail -> userEmail as read
// MUST be defined before /:id so Express does not swallow "read" as an id param
router.patch('/read', async (req, res) => {
  try {
    const userEmail  = (req.query.userEmail  || '').trim().toLowerCase();
    const otherEmail = (req.query.otherEmail || '').trim().toLowerCase();
    if (!userEmail || !otherEmail) return res.status(400).json({ error: 'userEmail and otherEmail required' });

    const readAt = new Date().toISOString();
    const { data: updatedRows, error } = await supabase
      .from('messages')
      .update({ read_at: readAt })
      .eq('sender_email', otherEmail)
      .eq('recipient_email', userEmail)
      .is('read_at', null)
      .select('id');

    if (error) return res.status(500).json({ error: error.message });

    const markedCount = Array.isArray(updatedRows) ? updatedRows.length : 0;
    logNotificationDebug('Marked conversation as read', { userEmail, otherEmail, markedCount });
    res.json({ success: true, markedCount, markedAt: readAt });
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

