// Extract Prod schema DDL via Supabase Management API (no DB password needed)
const TOKEN = process.env.SUPABASE_ACCESS_TOKEN;
const REF = process.env.SRC_REF;
const fs = require('fs');

async function q(sql) {
  const r = await fetch(`https://api.supabase.com/v1/projects/${REF}/database/query`, {
    method: 'POST',
    headers: { Authorization: `Bearer ${TOKEN}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({ query: sql }),
  });
  const t = await r.text();
  if (!r.ok) throw new Error(`HTTP ${r.status}: ${t.slice(0, 500)}\nSQL: ${sql.slice(0, 200)}`);
  return JSON.parse(t);
}

const out = [];
const S = (s) => out.push(s);

(async () => {
  S('-- Aivorah baseline schema, extracted from production');
  S(`-- source project: ${REF}`);
  S(`-- generated: ${new Date().toISOString()}`);
  S('');

  // 1. Extensions
  const exts = await q(`select e.extname, n.nspname as schema
    from pg_extension e join pg_namespace n on n.oid = e.extnamespace
    where e.extname not in ('plpgsql') order by 1`);
  S('-- ============ EXTENSIONS ============');
  for (const e of exts) S(`create extension if not exists "${e.extname}" with schema ${e.schema};`);
  S('');

  // 2. Schemas (non-system, excluding supabase-managed)
  const schemas = await q(`select nspname from pg_namespace
    where nspname not in ('pg_catalog','information_schema','pg_toast','public',
      'auth','storage','extensions','graphql','graphql_public','realtime','vault','supabase_functions','supabase_migrations','pgbouncer','net','cron','pgsodium','pgsodium_masks')
    and nspname not like 'pg_temp%' and nspname not like 'pg_toast%' order by 1`);
  if (schemas.length) {
    S('-- ============ SCHEMAS ============');
    for (const s of schemas) S(`create schema if not exists "${s.nspname}";`);
    S('');
  }

  // 3. Enum types
  const enums = await q(`select n.nspname as schema, t.typname as name,
      string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder) as labels
    from pg_type t
    join pg_enum e on e.enumtypid = t.oid
    join pg_namespace n on n.oid = t.typnamespace
    where n.nspname = 'public'
    group by 1,2 order by 2`);
  if (enums.length) {
    S('-- ============ ENUM TYPES ============');
    for (const e of enums) {
      S(`do $$ begin
  if not exists (select 1 from pg_type t join pg_namespace n on n.oid = t.typnamespace
                 where n.nspname = '${e.schema}' and t.typname = '${e.name}') then
    create type "${e.schema}"."${e.name}" as enum (${e.labels});
  end if;
end $$;`);
    }
    S('');
  }

  // 4. Composite/domain types
  const domains = await q(`select n.nspname as schema, t.typname as name,
      pg_catalog.format_type(t.typbasetype, t.typtypmod) as base,
      t.typnotnull as notnull, t.typdefault as def
    from pg_type t join pg_namespace n on n.oid = t.typnamespace
    where n.nspname='public' and t.typtype='d' order by 2`);
  if (domains.length) {
    S('-- ============ DOMAINS ============');
    for (const d of domains) {
      S(`create domain "${d.schema}"."${d.name}" as ${d.base}${d.notnull ? ' not null' : ''}${d.def ? ` default ${d.def}` : ''};`);
    }
    S('');
  }

  // 5. Sequences
  const seqs = await q(`select sequence_schema, sequence_name from information_schema.sequences
    where sequence_schema = 'public' order by 2`);
  if (seqs.length) {
    S('-- ============ SEQUENCES ============');
    for (const s of seqs) S(`create sequence if not exists "${s.sequence_schema}"."${s.sequence_name}";`);
    S('');
  }

  // 6. Tables + columns
  const cols = await q(`select c.relname as tbl, a.attname as col,
      pg_catalog.format_type(a.atttypid, a.atttypmod) as coltype,
      a.attnotnull as notnull,
      pg_get_expr(d.adbin, d.adrelid) as def,
      a.attidentity as identity,
      a.attgenerated as generated,
      a.attnum
    from pg_attribute a
    join pg_class c on c.oid = a.attrelid
    join pg_namespace n on n.oid = c.relnamespace
    left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
    where n.nspname = 'public' and c.relkind = 'r'
      and a.attnum > 0 and not a.attisdropped
    order by c.relname, a.attnum`);

  const byTable = {};
  for (const c of cols) (byTable[c.tbl] ||= []).push(c);

  S('-- ============ TABLES ============');
  for (const [tbl, list] of Object.entries(byTable)) {
    const lines = list.map((c) => {
      let l = `  "${c.col}" ${c.coltype}`;
      if (c.identity === 'a') l += ' generated always as identity';
      else if (c.identity === 'd') l += ' generated by default as identity';
      else if (c.generated === 's') l += ` generated always as (${c.def}) stored`;
      else if (c.def) l += ` default ${c.def}`;
      if (c.notnull && c.generated !== 's') l += ' not null';
      return l;
    });
    S(`create table if not exists "public"."${tbl}" (\n${lines.join(',\n')}\n);`);
  }
  S('');

  // 7. Constraints — PK/UNIQUE first, then CHECK, then FK
  const cons = await q(`select c.relname as tbl, con.conname as name,
      pg_get_constraintdef(con.oid) as def, con.contype
    from pg_constraint con
    join pg_class c on c.oid = con.conrelid
    join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and c.relkind = 'r'
    order by case con.contype when 'p' then 1 when 'u' then 2 when 'c' then 3 else 4 end, c.relname`);
  S('-- ============ CONSTRAINTS ============');
  for (const c of cons) {
    S(`do $$ begin
  if not exists (select 1 from pg_constraint con
                 join pg_class r on r.oid = con.conrelid
                 join pg_namespace n on n.oid = r.relnamespace
                 where n.nspname = 'public' and r.relname = '${c.tbl}' and con.conname = '${c.name}') then
    alter table "public"."${c.tbl}" add constraint "${c.name}" ${c.def};
  end if;
end $$;`);
  }
  S('');

  // 8. Indexes (skip ones backing constraints)
  const conNames = new Set(cons.map((c) => c.name));
  const idx = await q(`select indexname, indexdef from pg_indexes where schemaname = 'public' order by 1`);
  S('-- ============ INDEXES ============');
  for (const i of idx) {
    if (conNames.has(i.indexname)) continue;
    S(i.indexdef.replace(/^CREATE INDEX /i, 'CREATE INDEX IF NOT EXISTS ')
                .replace(/^CREATE UNIQUE INDEX /i, 'CREATE UNIQUE INDEX IF NOT EXISTS ') + ';');
  }
  S('');

  // 9. Views
  const views = await q(`select table_name, view_definition from information_schema.views
    where table_schema='public' order by 1`);
  if (views.length) {
    S('-- ============ VIEWS ============');
    for (const v of views) S(`create or replace view "public"."${v.table_name}" as\n${v.view_definition}`);
    S('');
  }

  // 10. Functions
  const fns = await q(`select pg_get_functiondef(p.oid) as def
    from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' and p.prokind in ('f','p')
    order by p.proname`);
  if (fns.length) {
    S('-- ============ FUNCTIONS ============');
    for (const f of fns) S(f.def + ';\n');
    S('');
  }

  // 11. Triggers
  const trgs = await q(`select pg_get_triggerdef(t.oid) as def
    from pg_trigger t
    join pg_class c on c.oid = t.tgrelid
    join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and not t.tgisinternal
    order by c.relname, t.tgname`);
  if (trgs.length) {
    S('-- ============ TRIGGERS ============');
    for (const t of trgs) S(t.def + ';');
    S('');
  }

  // 12. RLS enable
  const rls = await q(`select c.relname, c.relrowsecurity, c.relforcerowsecurity
    from pg_class c join pg_namespace n on n.oid = c.relnamespace
    where n.nspname='public' and c.relkind='r' and c.relrowsecurity
    order by 1`);
  S('-- ============ ROW LEVEL SECURITY ============');
  for (const r of rls) {
    S(`alter table "public"."${r.relname}" enable row level security;`);
    if (r.relforcerowsecurity) S(`alter table "public"."${r.relname}" force row level security;`);
  }
  S('');

  // 13. Policies
  const pols = await q(`select schemaname, tablename, policyname, permissive, roles, cmd, qual, with_check
    from pg_policies where schemaname='public' order by tablename, policyname`);
  if (pols.length) {
    S('-- ============ POLICIES ============');
    for (const p of pols) {
      const roles = (p.roles || '{public}').replace(/[{}]/g, '').split(',').filter(Boolean).map((r) => `"${r.trim()}"`).join(', ');
      let s = `create policy "${p.policyname}" on "public"."${p.tablename}"`;
      s += ` as ${p.permissive === 'PERMISSIVE' ? 'permissive' : 'restrictive'}`;
      s += ` for ${p.cmd.toLowerCase()}`;
      s += ` to ${roles || 'public'}`;
      if (p.qual) s += ` using (${p.qual})`;
      if (p.with_check) s += ` with check (${p.with_check})`;
      S(`do $$ begin
  if not exists (select 1 from pg_policies
                 where schemaname = 'public' and tablename = '${p.tablename}' and policyname = '${p.policyname}') then
    ${s};
  end if;
end $$;`);
    }
    S('');
  }

  // 14. Grants on tables
  const grants = await q(`select table_name, grantee, string_agg(privilege_type, ', ') as privs
    from information_schema.role_table_grants
    where table_schema='public' and grantee in ('anon','authenticated','service_role')
    group by 1,2 order by 1,2`);
  if (grants.length) {
    S('-- ============ GRANTS ============');
    for (const g of grants) S(`grant ${g.privs} on table "public"."${g.table_name}" to "${g.grantee}";`);
    S('');
  }

  const sql = out.join('\n');
  fs.writeFileSync(process.env.OUT_FILE, sql);
  console.error(`WROTE ${process.env.OUT_FILE}`);
  console.error(`tables=${Object.keys(byTable).length} constraints=${cons.length} indexes=${idx.length} views=${views.length} functions=${fns.length} triggers=${trgs.length} rls_tables=${rls.length} policies=${pols.length} enums=${enums.length} extensions=${exts.length} sequences=${seqs.length}`);
})().catch((e) => { console.error('FAILED:', e.message); process.exit(1); });
